import * as v from 'valibot';

export const notificationLimits = {
  bodyBytes: 65536,
  recipients: 100,
  endpoints: 1000,
  ttlSeconds: 2419200,
} as const;

const textSchema = v.pipe(v.string(), v.regex(/^[^\uD800-\uDFFF]*$/u));
const idSchema = v.pipe(v.string(), v.uuid(), v.toLowerCase());
const dataKeySchema = v.pipe(
  textSchema,
  v.minLength(1),
  v.check(
    (key) =>
      !['notificationId', 'deliveryId', 'aps', 'from', 'message_type', 'collapse_key'].includes(
        key,
      ) &&
      !key.startsWith('google.') &&
      !key.startsWith('gcm.'),
    'Reserved application data key',
  ),
);
const alertSchema = v.strictObject({
  title: v.pipe(textSchema, v.minLength(1)),
  body: v.pipe(textSchema, v.minLength(1)),
});
const apnsOverrideSchema = v.variant('pushType', [
  v.strictObject({
    pushType: v.literal('alert'),
    priority: v.optional(v.union([v.literal(5), v.literal(10)]), 10),
    collapseId: v.optional(
      v.pipe(
        textSchema,
        v.minLength(1),
        v.check((value) => Buffer.byteLength(value) <= 64),
      ),
    ),
    sound: v.optional(v.pipe(textSchema, v.minLength(1))),
    badge: v.optional(v.pipe(v.number(), v.integer(), v.minValue(0), v.maxValue(2147483647))),
  }),
  v.strictObject({
    pushType: v.literal('background'),
    priority: v.optional(v.literal(5), 5),
    collapseId: v.optional(
      v.pipe(
        textSchema,
        v.minLength(1),
        v.check((value) => Buffer.byteLength(value) <= 64),
      ),
    ),
  }),
]);

/**
 * Validates bounded explicit targets, common content, absolute expiry, and supported overrides.
 * Unknown fields and reserved data keys are rejected. Expiry relative to the clock is
 * checked by parseNotificationRequest. Targets are deduplicated during acceptance.
 * @example
 * ```ts
 * const request = v.parse(notificationRequestSchema, body);
 * ```
 */
export const notificationRequestSchema = v.pipe(
  v.strictObject({
    targets: v.variant('kind', [
      v.strictObject({
        kind: v.literal('recipients'),
        ids: v.pipe(v.array(idSchema), v.minLength(1), v.maxLength(notificationLimits.recipients)),
      }),
      v.strictObject({
        kind: v.literal('endpoints'),
        ids: v.pipe(v.array(idSchema), v.minLength(1), v.maxLength(notificationLimits.endpoints)),
      }),
    ]),
    content: v.strictObject({
      alert: v.optional(alertSchema),
      data: v.optional(v.record(dataKeySchema, textSchema), {}),
    }),
    expiresAt: v.pipe(
      v.string(),
      v.isoTimestamp(),
      v.check(
        (value) =>
          Number.isFinite(Date.parse(value)) &&
          new Date(`${value.slice(0, 10)}T00:00:00.000Z`).toISOString().slice(0, 10) ===
            value.slice(0, 10),
      ),
      v.transform((value) => new Date(value).toISOString()),
    ),
    overrides: v.optional(
      v.strictObject({
        apns: v.optional(apnsOverrideSchema),
        fcm: v.optional(
          v.strictObject({
            priority: v.optional(v.picklist(['NORMAL', 'HIGH']), 'NORMAL'),
            collapseKey: v.optional(v.pipe(textSchema, v.minLength(1), v.maxCodePoints(64))),
          }),
        ),
        webPush: v.optional(
          v.strictObject({
            urgency: v.optional(v.picklist(['very-low', 'low', 'normal', 'high']), 'normal'),
            topic: v.optional(v.pipe(v.string(), v.regex(/^[A-Za-z0-9_-]{1,32}$/))),
          }),
        ),
      }),
      {},
    ),
  }),
  v.check(
    (request) =>
      request.content.alert !== undefined || Object.keys(request.content.data).length > 0,
    'Content must contain an alert or application data',
  ),
  v.check(
    (request) =>
      request.overrides.apns?.pushType !== 'alert' || request.content.alert !== undefined,
    'Alert APNs pushes require an alert',
  ),
  v.check(
    (request) =>
      request.overrides.apns?.pushType !== 'background' || request.content.alert === undefined,
    'Background APNs pushes cannot contain an alert',
  ),
);
export type NotificationRequest = v.InferOutput<typeof notificationRequestSchema>;
export type ApiProblem = {
  type: 'about:blank';
  title: 'Invalid request' | 'Content too large';
  status: 413 | 422;
  code:
    | 'NOTIFICATION_BODY_TOO_LARGE'
    | 'NOTIFICATION_INVALID'
    | 'NOTIFICATION_EXPIRY_INVALID'
    | 'NOTIFICATION_PAYLOAD_TOO_LARGE'
    | 'NOTIFICATION_NO_TARGETS'
    | 'NOTIFICATION_TARGET_LIMIT_EXCEEDED';
  requestId: string;
  invalidParams?: { pointer: string }[];
};
type NotificationFailure = { ok: false; problem: ApiProblem };
export type NotificationResult<Value> = { ok: true; value: Value } | NotificationFailure;

/**
 * Creates a safe RFC 9457 failure without including request content or provider secrets.
 * @param code - Stable notification failure code.
 * @param requestId - Correlation ID generated by the HTTP boundary.
 * @returns A failure result with status 413 for body size, otherwise 422.
 * @example
 * ```ts
 * return notificationFailure('NOTIFICATION_NO_TARGETS', requestId);
 * ```
 */
export function notificationFailure(
  code: ApiProblem['code'],
  requestId: string,
): NotificationFailure {
  const status = code === 'NOTIFICATION_BODY_TOO_LARGE' ? 413 : 422;
  return {
    ok: false,
    problem: {
      type: 'about:blank',
      title: status === 413 ? 'Content too large' : 'Invalid request',
      status,
      code,
      requestId,
    },
  };
}

/**
 * Parses a bounded JSON body and validates expiry against the acceptance clock.
 * The HTTP adapter must also bound streaming reads before buffering the body.
 * @param body - Raw UTF-8 JSON body.
 * @param now - Acceptance time in epoch milliseconds.
 * @param requestId - Server-generated correlation ID.
 * @returns A validated request or safe problem details. Expiry must be in the future and at most 28 days away.
 * @example
 * ```ts
 * const result = parseNotificationRequest(body, Date.now(), requestId);
 * ```
 */
export function parseNotificationRequest(
  body: string,
  now: number,
  requestId: string,
): NotificationResult<NotificationRequest> {
  if (Buffer.byteLength(body) > notificationLimits.bodyBytes) {
    return notificationFailure('NOTIFICATION_BODY_TOO_LARGE', requestId);
  }

  try {
    const parsed = v.safeParse(notificationRequestSchema, JSON.parse(body));
    if (!parsed.success) {
      const failure = notificationFailure('NOTIFICATION_INVALID', requestId);
      const pointers = new Set<string>();
      for (const issue of parsed.issues) {
        const field = issue.path?.[0]?.key;
        const pointer = ['targets', 'content', 'expiresAt', 'overrides'].find(
          (entry) => entry === field,
        );
        pointers.add(pointer ? `/${pointer}` : '');
      }
      failure.problem.invalidParams = [...pointers].map((pointer) => ({ pointer }));
      return failure;
    }

    const remaining = Date.parse(parsed.output.expiresAt) - now;
    if (
      !Number.isFinite(now) ||
      remaining < 1000 ||
      remaining > notificationLimits.ttlSeconds * 1000
    ) {
      return notificationFailure('NOTIFICATION_EXPIRY_INVALID', requestId);
    }

    return { ok: true, value: parsed.output };
  } catch {
    return notificationFailure('NOTIFICATION_INVALID', requestId);
  }
}

/**
 * Deduplicates resolved endpoint IDs and enforces the acceptance expansion bound.
 * Call inside the authorized acceptance transaction after resolving active endpoints.
 * @param endpointIds - Resolved IDs from the scoped database query.
 * @param requestId - Server-generated correlation ID.
 * @returns Unique IDs, or a no-targets/target-limit failure before any queue insertion.
 * @example
 * ```ts
 * const targets = boundNotificationTargets(resolvedIds, requestId);
 * ```
 */
export function boundNotificationTargets(
  endpointIds: Iterable<string>,
  requestId: string,
): NotificationResult<string[]> {
  const ids = new Set<string>();
  for (const id of endpointIds) {
    ids.add(id);
    if (ids.size > notificationLimits.endpoints) {
      return notificationFailure('NOTIFICATION_TARGET_LIMIT_EXCEEDED', requestId);
    }
  }

  if (ids.size === 0) {
    return notificationFailure('NOTIFICATION_NO_TARGETS', requestId);
  }

  return { ok: true, value: [...ids] };
}
